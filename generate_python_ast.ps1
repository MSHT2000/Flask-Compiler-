$utf8 = New-Object System.Text.UTF8Encoding($false)

function Gen($def) {
    $p = $def.Trim() -split '\|'
    $name = $p[0]; $parent = $p[1]; $kind = $p[2]
    $fieldsRaw = if ($p.Count -gt 3) { $p[3] } else { "" }
    if ($kind -eq 'A') {
        [System.IO.File]::WriteAllText((Join-Path $root "$name.java"), "package AST.Python;`n`npublic abstract class $name {`n}`n", $utf8)
        return
    }
    $decls=@(); $params=@(); $assigns=@(); $accs=@()
    if ($fieldsRaw) {
        foreach ($f in ($fieldsRaw -split ';')) {
            $fp = $f -split ':'
            $ft = $fp[0]; $fn = $fp[1]
            $decls += "    public $ft $fn;"
            $params += "$ft $fn"
            $assigns += "        this.$fn = $fn;"
            $cap = $fn.Substring(0,1).ToUpper() + $fn.Substring(1)
            $accs += "    public $ft get$cap() { return $fn; }"
            $accs += "    public void set$cap($ft $fn) { this.$fn = $fn; }"
        }
    }
    $ext = if ($parent) { " extends $parent" } else { "" }
    $ctor = if ($params.Count) { ", " + ($params -join ', ') } else { "" }
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("package AST.Python;")
    [void]$sb.AppendLine("import java.lang.String;")
    [void]$sb.AppendLine("import java.util.List;")
    [void]$sb.AppendLine("public class $name$ext {")
    [void]$sb.AppendLine("    public String nodeName;")
    [void]$sb.AppendLine("    public int lineNumber;")
    $decls | % { [void]$sb.AppendLine($_) }
    [void]$sb.AppendLine("    public $name() { }")
    [void]$sb.AppendLine("    public $name(String nodeName, int lineNumber$ctor) {")
    [void]$sb.AppendLine("        this.nodeName = nodeName;")
    [void]$sb.AppendLine("        this.lineNumber = lineNumber;")
    $assigns | % { [void]$sb.AppendLine($_) }
    [void]$sb.AppendLine("    }")
    [void]$sb.AppendLine("    public String getNodeName() { return nodeName; }")
    [void]$sb.AppendLine("    public void setNodeName(String nodeName) { this.nodeName = nodeName; }")
    [void]$sb.AppendLine("    public int getLineNumber() { return lineNumber; }")
    [void]$sb.AppendLine("    public void setLineNumber(int lineNumber) { this.lineNumber = lineNumber; }")
    $accs | % { [void]$sb.AppendLine($_) }
    [void]$sb.AppendLine("    @Override")
    [void]$sb.AppendLine('    public String toString() { return ""; }')
    [void]$sb.AppendLine("}")
    [System.IO.File]::WriteAllText((Join-Path $root "$name.java"), $sb.ToString(), $utf8)
}

